/** Product help never needs patient documents or an external model. */
export function productGuide(question: string): string | null {
  if (question.startsWith("Обсудить ")) return null;
  const q = question.toLowerCase();
  if (/как.*(?:загруз|добавить файл)|какие (?:файлы|форматы)|фото.*(?:телефон|загруз)/u.test(q))
    return "Откройте «Документы» и нажмите «Загрузить документы». Выберите файл или «Готовый PNG или JPEG». «Со смартфона» показывает QR-код для загрузки с телефона. После обработки откройте «Разбор».";
  if (/кто ты|что (?:умеет|такое) (?:атлаксис|atlaxis)|обзор приложения|проведи.*приложени/u.test(q))
    return "Я — Профессор, цифровой помощник Атлаксиса. Помогу освоить приложение и пояснить уже собранные сведения. В «Документах» загружают анализы, выписки и снимки; в «Разборе» смотрят динамику, расхождения и источники. С чего начнём — с загрузки или просмотра разбора? Диагноз и лечение сервис не назначает.";
  if (/как.*(?:профессор|отправить находку)|что (?:делает|умеет) профессор/u.test(q))
    return "В «Разборе» кнопка «Профессору» отправляет одну находку, а «Весь разбор профессору» — комплект целиком. Я поясню уже записанное, без диагноза и назначения лечения.";
  if (/(?:цена|стоимость|подписк|тариф).*(?:атлаксис|atlaxis|приложени)|сколько стоит (?:атлаксис|atlaxis|подписка)/u.test(q))
    return "Подтверждённых сведений о стоимости и подписке у меня нет. Их нужно уточнить у автора Атлаксиса.";
  return null;
}
